import { randomBytes } from "node:crypto";

export const PUBLIC_CONFIG_MARKER = "# EnderChest generated public configuration";

function hostname(value) {
  if (!/^[a-z0-9-]+(?:\.[a-z0-9-]+)+$/i.test(value) || value.length > 253 || value.split(".").some(part => part.length > 63 || part.startsWith("-") || part.endsWith("-"))) {
    throw new Error("Enter a valid hostname without a scheme or path.");
  }
  return value.toLowerCase();
}

function httpsOrigin(value) {
  let url;
  try { url = new URL(value); } catch { throw new Error("Enter a full HTTPS URL."); }
  if (url.protocol !== "https:" || !url.hostname || url.username || url.password || url.pathname !== "/" || url.search || url.hash || url.port) {
    throw new Error("Enter a root HTTPS URL without a port, path, query, or credentials.");
  }
  return url.origin;
}

export function renderPublicConfig(mode, values, previous = "") {
  if (!["funnel", "provider", "domain"].includes(mode)) throw new Error("Choose funnel, provider, or domain.");
  let secret = randomBytes(32).toString("hex");
  if (previous) {
    if (!previous.startsWith(`${PUBLIC_CONFIG_MARKER}\n`)) throw new Error("Existing public configuration was not generated by EnderChest; no changes made.");
    const previousMode = /^PUBLIC_MODE=(funnel|provider|domain)$/m.exec(previous)?.[1];
    if (previousMode !== mode) throw new Error("Switching connection methods requires manual review; no changes made.");
    secret = /^PUBLIC_LINK_SECRET=([a-f0-9]{64})$/m.exec(previous)?.[1] ?? secret;
  }
  const lines = [PUBLIC_CONFIG_MARKER, `PUBLIC_MODE=${mode}`];
  if (mode === "domain") {
    const app = hostname(values[0] ?? "");
    const files = hostname(values[1] ?? "");
    if (app === files) throw new Error("App and file hostnames must differ.");
    lines.push(`DOMAIN=${app}`, `S3_PUBLIC_DOMAIN=${files}`);
  } else {
    const origin = httpsOrigin(values[0] ?? "");
    if (mode === "funnel" && !new URL(origin).hostname.endsWith(".ts.net")) throw new Error("Funnel must use its HTTPS .ts.net address.");
    lines.push(`PUBLIC_APP_URL=${origin}`);
  }
  lines.push(`PUBLIC_LINK_SECRET=${secret}`);
  return `${lines.join("\n")}\n`;
}
